WITH Planejamento AS (
    SELECT
        ANO_SEMESTRE,
        MATRICULA_PROFESSOR,

        SUM(CAST(CH_REAL_PROFESSOR_DISCIPLINA AS bigint))
            AS CH_PLANEJAMENTO_TOTAL,

        SUM(CASE
            WHEN VAGAS_PREENCHIDAS = 0
            THEN CAST(CH_REAL_PROFESSOR_DISCIPLINA AS bigint)
            ELSE 0
        END) AS CH_ZERO_VAGAS,

        SUM(CASE
            WHEN VAGAS_PREENCHIDAS <> 0
            THEN CAST(CH_REAL_PROFESSOR_DISCIPLINA AS bigint)
            ELSE 0
        END) AS CH_SEM_ZERO_VAGAS,

        SUM(CASE
            WHEN VAGAS_PREENCHIDAS IS NULL
            THEN 1 ELSE 0
        END) AS REGISTROS_VAGAS_NULAS,

        SUM(CASE
            WHEN CH_REAL_PROFESSOR_DISCIPLINA IS NULL
            THEN 1 ELSE 0
        END) AS REGISTROS_CH_NULA

    FROM dbo.V_PLANEJAMENTO
    WHERE ANO_SEMESTRE = 20262
      AND NOME_PROFESSOR NOT IN (
        'HORISTA A CONTRATAR',
        'TEMPO CONTINUO A DEFINIR',
        'RECEM-DOUTOR',
        'COORDENADOR DE CURSO',
        'PROFESSOR DO CCE',
        'PALESTRANTE'
      )
    GROUP BY
        ANO_SEMESTRE,
        MATRICULA_PROFESSOR
),
HorasReais AS (
    SELECT
        *,
        COUNT(*) OVER (
            PARTITION BY SEMESTRE, MATRICULA_PRF
        ) AS REGISTROS_PROFESSOR_SEMESTRE
    FROM dbo.V_HORAS_REAIS_PROF
    WHERE SEMESTRE = 20262
)
SELECT
    p.ANO_SEMESTRE,
    p.MATRICULA_PROFESSOR,
    r.NOME_PROFESSOR,
    r.DEPTO_PROF,
    r.HORAS_REAIS,

    p.CH_PLANEJAMENTO_TOTAL,
    p.CH_ZERO_VAGAS,
    p.CH_SEM_ZERO_VAGAS,

    CASE
        WHEN p.REGISTROS_CH_NULA = 0
         AND r.REGISTROS_PROFESSOR_SEMESTRE = 1
        THEN p.CH_PLANEJAMENTO_TOTAL - r.HORAS_REAIS
    END AS DIF_TOTAL_MENOS_HORAS_REAIS,

    CASE
        WHEN p.REGISTROS_CH_NULA = 0
         AND p.REGISTROS_VAGAS_NULAS = 0
         AND r.REGISTROS_PROFESSOR_SEMESTRE = 1
        THEN p.CH_SEM_ZERO_VAGAS - r.HORAS_REAIS
    END AS DIF_SEM_ZERO_MENOS_HORAS_REAIS,

    p.REGISTROS_VAGAS_NULAS,
    p.REGISTROS_CH_NULA,
    r.REGISTROS_PROFESSOR_SEMESTRE

FROM Planejamento AS p
LEFT JOIN HorasReais AS r
    ON r.MATRICULA_PRF = p.MATRICULA_PROFESSOR
   AND r.SEMESTRE = p.ANO_SEMESTRE

ORDER BY
    p.CH_ZERO_VAGAS DESC,
    p.MATRICULA_PROFESSOR;
